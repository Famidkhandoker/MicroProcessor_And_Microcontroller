.MODEL SMALL
.STACK 100H
.DATA

A DW 4
B DW 5
C DW 4

STR1 DB "EQUILATERAL$"
STR2 DB "ISOSCELES$"
STR3 DB "SCALENE$"

.CODE
MAIN PROC
    MOV AX,@DATA
    MOV DS,AX

    MOV AX,A
    CMP AX,B
    JNE CHECK

    CMP AX,C
    JE EQUILATERAL

    JMP ISOSCELES

CHECK:
    MOV AX,B
    CMP AX,C
    JE ISOSCELES

    MOV AX,A
    CMP AX,C
    JE ISOSCELES

    JMP SCALENE

EQUILATERAL: 
    MOV AH,9
    LEA DX,STR1
    INT 21H
    JMP EXIT

ISOSCELES:
    MOV AH,9
    LEA DX,STR2
    INT 21H
    JMP EXIT

SCALENE:
    MOV AH,9
    LEA DX,STR3
    INT 21H

EXIT:
MAIN ENDP
END MAIN